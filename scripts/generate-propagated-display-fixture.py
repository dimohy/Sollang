"""Derive a four-case semantic boundary fixture with the canonical compiler closure."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/probes/interpolation/c527-preir-propagated-display-aligned-facts.slg'
CONTRACT = ROOT / 'artifacts/scratch/resume-rootfc1a-propagated-display-facts-contract-after90-20261003-01.json'
NAME = '2489-preir-propagated-display-invariant'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contract = json.loads(CONTRACT.read_text(encoding='utf-8-sig'))
    case = contract['cases'][0]
    if len(contract['cases']) != 1 or case['source'] != SOURCE.relative_to(ROOT).as_posix():
        raise ValueError('PROPAGATED_DISPLAY_SOURCE_CONTRACT_CHANGED')
    canonical = (ROOT / 'tests/Sollang.ExampleTests/Fixtures/selfhost-sollangc-driver.sources.txt').read_text(encoding='utf-8-sig').splitlines()
    if not canonical or canonical[0] != 'tests/Sollang.ExampleTests/Fixtures/selfhost-sollangc-driver.slg':
        raise ValueError('PROPAGATED_DISPLAY_CANONICAL_ENTRY_CHANGED')
    shared = canonical[1:]
    if not shared or len(set(shared)) != len(shared) or any(not (ROOT / path).is_file() for path in shared):
        raise ValueError('PROPAGATED_DISPLAY_SHARED_SOURCE_CLOSURE_CHANGED')
    source = '# Generated by scripts/generate-propagated-display-fixture.py; edit the source probe.\n' + SOURCE.read_text(encoding="utf-8")
    outputs = {
        ROOT / f'examples/regression/{NAME}.slg': source,
        ROOT / f'examples/regression/expected/{NAME}.sources.txt': '\n'.join([f'examples/regression/{NAME}.slg', *shared]) + '\n',
        ROOT / f'examples/regression/expected/{NAME}.stdout.txt': case['stdout'] + '\n',
    }
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode('utf-8'):
                raise ValueError('PROPAGATED_DISPLAY_GENERATED_FIXTURE_DRIFT: ' + str(path))
        else:
            path.write_bytes(content.encode('utf-8'))
    print('PROPAGATED_DISPLAY_FIXTURE_CHECKED' if args.check else 'PROPAGATED_DISPLAY_FIXTURE_GENERATED')


if __name__ == '__main__':
    main()
