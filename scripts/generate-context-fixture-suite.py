"""Derive one executable suite from the four direct EmitContext fixtures."""

import argparse
from pathlib import Path
import runpy
import subprocess


ROOT = Path(__file__).resolve().parent.parent
NAMES = (
    "1000-selfhost-partition-route-type-invariant",
    "1100-selfhost-enum-match-variant-invariant",
    "1126-selfhost-console-emission-invariant",
    "1290-selfhost-provisional-unit-match-invariant",
)
SUITE = "1999-selfhost-context-fixture-suite"


def render() -> tuple[str, str, str]:
    def literal(path: Path) -> str:
        return "'" + str(path).replace("'", "''") + "'"
    manifests = [ROOT / 'examples/regression/expected' / f'{name}.sources.txt' for name in NAMES]
    command = (f"& {literal(ROOT / 'scripts/verify-source-manifest-closure.ps1')} "
               f"-Manifest @({','.join(literal(path) for path in manifests)}) "
               f"-SourcePath @(Get-ChildItem -LiteralPath {literal(ROOT / 'stdlib')} "
               "-Recurse -Filter '*.slg' | ForEach-Object FullName)")
    subprocess.run(['pwsh', '-NoProfile', '-Command', command], cwd=ROOT, check=True)
    verify = runpy.run_path(str(ROOT / 'scripts/verify-context-fixture-initializers.py'))['verify']
    verify([ROOT / 'examples/regression' / f'{name}.slg' for name in NAMES])
    imports: list[str] = []
    functions: list[str] = []
    calls: list[str] = []
    expected: list[str] = []
    shared_sources: list[str] | None = None
    for name in NAMES:
        source_path = ROOT / "examples/regression" / f"{name}.slg"
        source = source_path.read_text(encoding="utf-8-sig")
        lines = source.splitlines()
        for line in lines:
            if line.startswith("import ") and line not in imports:
                imports.append(line)
        marker = "main {\n"
        if source.count(marker) != 1 or not source.endswith("\n}\n"):
            raise ValueError(f"direct fixture has no single terminal main: {name}")
        body = source.split(marker, 1)[1].rsplit("\n}\n", 1)[0]
        function = "case" + name.split("-", 1)[0]
        functions.append(f"{function}: -> Unit uses Console {{\n{body}\n}}")
        calls.extend((f'    "{name}:begin" -> println', f"    {function}()",
                      f'    "{name}:end" -> println'))
        output = (ROOT / "examples/regression/expected" / f"{name}.stdout.txt").read_text(encoding="utf-8-sig")
        expected.extend((f"{name}:begin\n", output, f"{name}:end\n"))
        manifest = (ROOT / "examples/regression/expected" / f"{name}.sources.txt").read_text(
            encoding="utf-8-sig").splitlines()
        if not manifest or manifest[0] != f"examples/regression/{name}.slg":
            raise ValueError(f"direct fixture manifest root changed: {name}")
        if shared_sources is None:
            shared_sources = manifest[1:]
        elif len(manifest[1:]) != len(shared_sources) or set(manifest[1:]) != set(shared_sources):
            raise ValueError(f"direct fixtures no longer share one source closure: {name}")
    if not shared_sources or len(shared_sources) != len(set(shared_sources)):
        raise ValueError("suite requires a nonempty unique shared compiler source closure")
    source = "\n".join(imports) + "\n\n# Generated by scripts/generate-context-fixture-suite.py from four direct fixtures.\n\n"
    source += "\n\n".join(functions) + "\n\nmain {\n" + "\n".join(calls) + "\n}\n"
    manifest = "\n".join((f"examples/regression/{SUITE}.slg", *shared_sources)) + "\n"
    return source, "".join(expected), manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output_dir = ROOT / "examples/regression"
    expected_dir = output_dir / "expected"
    contents = render()
    paths = (output_dir / f"{SUITE}.slg", expected_dir / f"{SUITE}.stdout.txt",
             expected_dir / f"{SUITE}.sources.txt")
    for path, content in zip(paths, contents):
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                raise ValueError(f"generated context fixture suite drifted: {path}")
        else:
            path.write_bytes(content.encode("utf-8"))
    print(f"[context suite] {'CHECK' if args.check else 'GENERATED'} 4 cases, "
          f"{len(contents[2].splitlines())} sources")


if __name__ == "__main__":
    main()
