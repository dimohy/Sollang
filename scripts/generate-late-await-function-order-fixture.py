"""Extract unchanged authoritative await ordering code for a small paired fixture."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "scripts/probes/selection-result/generated-late-await-function-order-core.slg"


def extract_struct(source, name):
    matches = re.findall(r"public struct " + re.escape(name) + r" \{\n.*?\n\}", source, re.DOTALL)
    if len(matches) != 1:
        raise ValueError("AWAIT_OWNER_FIXTURE_STRUCT_NOT_UNIQUE: " + name)
    return matches[0]


def generate():
    typed = ROOT / "selfhost/ir/typed.slg"
    lowering = ROOT / "selfhost/ir/typed/function_lowering.slg"
    types = typed.read_text(encoding="utf-8-sig")
    source = lowering.read_text(encoding="utf-8-sig")
    start = "public sealDirectAwaitFunctionOrder "
    end = "appendFunctionResult "
    if source.count(start) != 1 or source.count("\n" + end) != 1:
        raise ValueError("AWAIT_OWNER_FIXTURE_FUNCTION_BOUNDARIES_NOT_UNIQUE")
    functions = source.split(start, 1)[1].split("\n" + end, 1)[0].rstrip()
    functions = start + functions
    expected = ["sealDirectAwaitFunctionOrder", "relocateAwaitEdge", "relocateAwaitGenericPlans", "relocateAwaitGenericInstances"]
    actual = re.findall(r"^(?:public )?(\w+) .*->.*\{$", functions, re.MULTILINE)
    if actual != expected:
        raise ValueError("AWAIT_OWNER_FIXTURE_FUNCTION_SET_MISMATCH")
    body = ("namespace sollang.compiler.ir.typed\n\n"
            "# Generated by scripts/generate-late-await-function-order-fixture.py.\n"
            "# Types and function bodies are copied unchanged from authoritative sources.\n\n"
            + extract_struct(types, "TypedIrNode") + "\n\n"
            + extract_struct(source, "GenericCallPlan") + "\n\n"
            + extract_struct(source, "GenericFunctionInstance") + "\n\n" + functions + "\n")
    return body.encode("utf-8"), [typed, lowering]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body, inputs = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != body:
            raise ValueError("AWAIT_OWNER_GENERATED_FIXTURE_SOURCE_DRIFT")
    else:
        OUTPUT.write_bytes(body)
    print(json.dumps({"status": "passed", "functionCount": 4, "structCount": 3,
                      "sourceHashes": {path.relative_to(ROOT).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest().upper()
                                       for path in inputs}, "generatedSha256": hashlib.sha256(body).hexdigest().upper()}))


if __name__ == "__main__":
    main()
