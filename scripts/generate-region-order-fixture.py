"""Extract the unchanged region scheduler for small ordering probes.

This fixture observes scheduling events, not LLVM emission. Aggregate wrappers
are excluded and fail explicitly; it cannot prove the full emitter or C527.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "scripts/probes/region-order/generated-core.slg"


def function(path, name):
    source = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    match = re.search(r"^" + re.escape(name) + r" .*?^\}", source, re.M | re.S)
    if not match:
        raise ValueError("REGION_FIXTURE_FUNCTION_MISSING: " + name)
    return match.group().replace("emitterContext.EmitContext", "EmitContext").replace("typedIr.TypedIrNode", "TypedIrNode")


def generate():
    paths = [ROOT / path for path in ["selfhost/llvm/text/control.slg",
             "selfhost/llvm/text/core_calls.slg", "selfhost/llvm/text/ownership.slg",
             "selfhost/ir/typed.slg"]]
    typed = paths[3].read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    node = re.search(r"^public struct TypedIrNode \{.*?^\}", typed, re.M | re.S).group()
    control = paths[0].read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    projection = re.search(r"^struct RegionStatementProjection \{.*?^\}", control, re.M | re.S)
    if projection is None:
        raise ValueError("REGION_FIXTURE_PROJECTION_MISSING")
    body = '''# Generated by scripts/generate-region-order-fixture.py.
# Scheduler and helper bodies retain production logic; namespace qualifiers
# are removed to use this isolated data model. Event emission is observed.
import sys.io
import sys.process as process

'''+node+'''
struct AstNode { start: UIntSize }
struct SourceRange { astStart: Int }
struct EmitContext {
    pointerBitWidth: Int
    ir: [TypedIrNode; ~]
    nodes: [AstNode; ~]
    ranges: [SourceRange; ~]
}
struct CoreEmitterState { frozenFunctionEnds: [Int; ~] }
struct NodeAncestorRequest { nodeIndex: Int, ownerIndex: Int }

# These probes have no aggregate-value lookup. Reject any unplanned use.
aggregateValueIndex wrapperIndex: Int, context: ref EmitContext, state: ref CoreEmitterState -> Int {
    87 -> process.exit
    wrapperIndex
}
emitRegionOrder regionIndex: Int, emissionOrder: [Int], regionEventKinds: ref [Int; ~], regionOrder: ref [Int; ~], ifActive: mut [Bool; ~], ifThenReachesMerge: mut [Bool; ~], loopActive: mut [Bool; ~], initialRegionTerminated: Bool, context: ref EmitContext, state: ref CoreEmitterState -> Unit uses Console {
    0 => index!
    index! < (regionOrder -> len) -> while {
        "$(regionEventKinds[index!]):$(regionOrder[index!])" -> println
        index! + 1 => index!
    }
}

'''
    body += projection.group() + "\n\n"
    for path, name in [(paths[1], "functionEnd"), (paths[1], "irDescendsFrom"),
                       (paths[2], "sourceStart"), (paths[0], "localSchedulePending"),
                       (paths[0], "prepareRegionStatementProjection"),
                       (paths[0], "projectRegionStatement"),
                       (paths[0], "regionPreviousStatementPending"),
                       (paths[0], "emitRegion")]:
        body += function(path, name) + "\n\n"
    return (body.rstrip() + "\n").encode("utf-8"), paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body, paths = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != body:
            raise ValueError("REGION_FIXTURE_SOURCE_DRIFT")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(body)
    print(json.dumps({"status": "passed", "scope": "scheduler-events-only",
                      "sourceHashes": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest().upper() for p in paths},
                      "fixtureSha256": hashlib.sha256(body).hexdigest().upper()}))


if __name__ == "__main__":
    main()
